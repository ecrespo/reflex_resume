def slice_key(period: str, profile: str) -> str:
    """The `slices` key for a period key and a profile name ("all" for every profile)."""
    return f"{period}|{profile}"


def get_slice(period: str, profile: str) -> dict[str, Any]:
    """The slice for a period and a profile, falling back to all time / all profiles."""
    return (
        SLICES.get(slice_key(period, profile)) or SLICES[slice_key(DEFAULT_PERIOD, DEFAULT_PROFILE)]
    )


