_PREFIXES = (("reflex-", "rx-"), ("reflex_", "rx_"), ("python-", "py-"), ("prismal-", "pr-"))


def short_label(name: str) -> str:
    """A label that fits the row-chart label column (at most `LABEL_CHARS`)."""
    label = _ALIASES.get(name, name)
    for prefix, short in _PREFIXES:
        if label.startswith(prefix):
            label = short + label[len(prefix) :]
            break
    # The ellipsis is wider than a letter, so a truncated label keeps one character less.
    return label if len(label) <= LABEL_CHARS else label[: LABEL_CHARS - 2] + "…"


def _label_rows(rows: list[dict[str, Any]], field: str) -> list[dict[str, Any]]:
    return [{**row, "label": short_label(str(row[field]))} for row in rows]


